import { createHash } from 'node:crypto'
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, relative, sep } from 'node:path'
import { fileURLToPath } from 'node:url'

const repoRoot = dirname(dirname(fileURLToPath(import.meta.url)))
const appRoot = join(repoRoot, 'app')
const serviceWorkerPath = join(appRoot, 'sw.js')
const generatorSource = readFileSync(fileURLToPath(import.meta.url))

const PRECACHE_EXTENSIONS = new Set([
  '.css',
  '.html',
  '.js',
  '.json',
  '.png',
  '.svg',
  '.webmanifest',
])

function toWebPath(filePath) {
  return filePath.split(sep).join('/')
}

function shouldPrecache(relativePath) {
  const webPath = toWebPath(relativePath)
  const fileName = webPath.split('/').at(-1)
  const extension = fileName.includes('.') ? `.${fileName.split('.').at(-1)}` : ''

  if (fileName.startsWith('.')) return false
  if (webPath === 'sw.js') return false
  if (webPath.endsWith('.test.js')) return false
  if (!PRECACHE_EXTENSIONS.has(extension)) return false

  return true
}

function collectFiles(directory) {
  return readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const absolutePath = join(directory, entry.name)
    const relativePath = relative(appRoot, absolutePath)

    if (entry.isDirectory()) {
      if (entry.name.startsWith('.')) return []
      return collectFiles(absolutePath)
    }

    if (!entry.isFile() || !shouldPrecache(relativePath)) {
      return []
    }

    return [relativePath]
  })
}

const precacheFiles = collectFiles(appRoot).sort((first, second) => first.localeCompare(second))
const precacheUrls = ['./', ...precacheFiles.map((file) => `./${toWebPath(file)}`)]

const hash = createHash('sha256')
hash.update(generatorSource)
precacheFiles.forEach((file) => {
  hash.update(toWebPath(file))
  hash.update('\0')
  hash.update(readFileSync(join(appRoot, file)))
  hash.update('\0')
})
const buildHash = hash.digest('hex').slice(0, 16)
const precacheUrlList = `[\n${precacheUrls.map((url) => `  '${url}',`).join('\n')}\n]`

const serviceWorkerSource = `/* Generated by scripts/generate-service-worker.mjs. Do not edit by hand. */
/* global caches, fetch, Request, self */
const CACHE_PREFIX = 'vj-tam-tam-app-'
const CACHE_NAME = CACHE_PREFIX + '${buildHash}'
const PRECACHE_URLS = ${precacheUrlList}

function cacheRequestFor(url) {
  return new Request(new URL(url, self.registration.scope), { cache: 'reload' })
}

function isAppShellRequest(request) {
  if (request.method !== 'GET') return false

  const url = new URL(request.url)
  if (url.origin !== self.location.origin) return false
  if (!url.href.startsWith(self.registration.scope)) return false

  return url.protocol === 'http:' || url.protocol === 'https:'
}

async function networkFirst(request) {
  const cache = await caches.open(CACHE_NAME)

  try {
    const response = await fetch(request)
    if (response?.ok) {
      await cache.put(request, response.clone())
    }
    return response
  } catch (error) {
    const cachedResponse = await cache.match(request)
    if (cachedResponse) {
      return cachedResponse
    }

    if (request.mode === 'navigate') {
      return cache.match(new URL('./index.html', self.registration.scope))
    }

    throw error
  }
}

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches
      .open(CACHE_NAME)
      .then((cache) => cache.addAll(PRECACHE_URLS.map(cacheRequestFor)))
      .then(() => self.skipWaiting())
  )
})

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((cacheNames) =>
        Promise.all(
          cacheNames
            .filter((cacheName) => cacheName.startsWith(CACHE_PREFIX) && cacheName !== CACHE_NAME)
            .map((cacheName) => caches.delete(cacheName))
        )
      )
      .then(() => self.clients.claim())
  )
})

self.addEventListener('fetch', (event) => {
  if (!isAppShellRequest(event.request)) {
    return
  }

  event.respondWith(networkFirst(event.request))
})
`

writeFileSync(serviceWorkerPath, serviceWorkerSource)
console.log(`Generated app/sw.js with ${precacheUrls.length} precached URLs (${buildHash})`)
